"""Every countable or checkable claim in the documents, held against the code (roadmap P8).

Four of these were wrong at once on 2026-11-05, and all four were the same defect the compliance document had
(G206): a number somebody typed, next to code that moved. `docs/limits.md` stated generated/not-generated pairs
that summed to 78 when there were 91 rules; `docs/use-cases.md` sold a compaction measurement from an older
rule set; `docs/editions.md` listed two capabilities under what a team gets free when neither exists; and "most
rules" described 47 of 91.

So the numbers are generated by `scripts/doc_numbers.py` and the rest is asserted here. A document is part of the
product: a buyer checks it, and a claim that fails the check is a defect, not stale prose.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import doc_numbers as dn  # noqa: E402

from kube_noob.cli import build_parser  # noqa: E402

DOCS = [
    ROOT / "README.md",
    ROOT / "docs" / "limits.md",
    ROOT / "docs" / "use-cases.md",
    ROOT / "docs" / "editions.md",
    ROOT / "docs" / "install.md",
    ROOT / "docs" / "operations.md",
    ROOT / "deploy" / "helm" / "kube-noob" / "README.md",
]


def test_the_committed_documents_are_current() -> None:
    assert dn.main(["--check"]) == 0, "run: python scripts/doc_numbers.py"


def test_the_generated_table_sums_to_the_rule_count() -> None:
    """Both published pairs summed to 78 with 91 rules in the code, because only one column was ever updated."""
    from kube_noob.audit.engine import list_rules

    rows = dn.policy_rows()
    assert rows, "the limits table has rows"
    for row in rows:
        assert row.generated + row.not_generated == len(list_rules()), row


def test_the_limits_table_states_the_measured_numbers() -> None:
    text = (ROOT / "docs" / "limits.md").read_text(encoding="utf-8")
    for row in dn.policy_rows():
        assert f"| {row.label} | {row.generated} | {row.not_generated} |" in text, row.label


def test_no_document_calls_a_minority_of_rules_most_of_them() -> None:
    """47 of 91 is not "most". A claim that is wrong by half is wrong, whatever the sentence around it does."""
    from kube_noob.audit.engine import list_rules

    rows = {r.label: r for r in dn.policy_rows()}
    assert max(r.generated for r in rows.values()) < len(list_rules())  # otherwise this test is vacuous
    for path in DOCS:
        text = path.read_text(encoding="utf-8")
        assert "admission policies for most rules" not in text, path.name


def test_the_compaction_measurement_is_the_one_the_code_produces() -> None:
    m = dn.compaction()
    text = (ROOT / "docs" / "use-cases.md").read_text(encoding="utf-8")
    assert f"{m.findings} findings over {m.rules} rules" in text
    assert dn.thousands(m.flat_bytes) in text and dn.thousands(m.compact_bytes) in text


def test_every_command_the_documents_name_exists() -> None:
    """`net verify` was advertised as a free capability and there is no `net` command at all.

    Asserted as "every documented invocation runs a command that exists" rather than "every word after kube-noob
    is a command", because the second shape produced false positives three times over: English verbs in prose,
    `kube-noob` appearing as an ARGUMENT to helm, brew and oci, and a global flag's value being read as the
    subcommand (`kube-noob --cluster-enabled posture scan` offered up `scan`).
    """
    parser = build_parser()
    subs = {name for action in parser._subparsers._group_actions for name in action.choices}
    bad: list[str] = []
    for path in DOCS:
        text = path.read_text(encoding="utf-8")
        # Fences paired from line starts: a ```yaml opener an earlier pattern did not recognise let one "block"
        # swallow the prose between two real blocks.
        snippets = re.findall(r"^```[a-zA-Z]*\n(.*?)^```", text, re.S | re.M) + re.findall(r"`([^`\n]+)`", text)
        for snippet in snippets:
            for line in snippet.splitlines():
                for raw in re.split(r"\||&&|;", line):
                    part = raw.strip().removeprefix("$ ")
                    if not part.startswith("kube-noob "):
                        continue  # `kube-noob` as an argument to another program is not an invocation
                    words = [w for w in part.split()[1:] if not w.startswith("-")][:4]
                    if not words:
                        continue  # `kube-noob --version` is a real invocation with no subcommand in it
                    if not any(w in subs for w in words):
                        bad.append(f"{path.name}: {part[:70]}")
    assert bad == [], f"documented invocations whose command does not exist: {bad}"
    # Proof the check can fail: the shape it was written for. `net` was advertised and never existed.
    assert "net" not in subs and "verify" not in subs


def test_the_free_list_names_nothing_that_is_not_built() -> None:
    """A page whose whole job is to draw the free/paid line must not promise an unbuilt analyser."""
    from kube_noob.insight import PENDING

    editions = (ROOT / "docs" / "editions.md").read_text(encoding="utf-8")
    heading = "## Free: everything one team needs"
    body = editions.split(heading, 1)[1].lstrip("\n")
    # The enumeration only: the paragraph directly under the heading. The prose after it explains what was
    # removed and why, and has to be able to name the thing it removed.
    enumerated = body.split("\n\n", 1)[0].lower()
    assert "pcap analyser" not in enumerated and "net verify" not in enumerated
    assert PENDING, "the pending map is what records an unbuilt analyser"
    for kind in PENDING:
        assert kind.replace("-", " ") not in enumerated, kind


def test_an_unbuilt_path_is_not_offered_as_a_runnable_example() -> None:
    """`insight -f trace.pcap` runs and reports the file as skipped. In a block of working commands it reads as
    a capability."""
    text = (ROOT / "docs" / "use-cases.md").read_text(encoding="utf-8")
    for block in re.findall(r"```bash\n(.*?)```", text, re.S):
        assert ".pcap" not in block, "a pcap command sits in a block of commands that work"


def test_the_scc_claim_says_what_ci_actually_proves() -> None:
    """`restricted-v2` is an OpenShift SCC and every CI leg is kind, so "runs under restricted-v2" is a claim no
    test backs. Pod Security `restricted` IS enforced in CI, and that is what the copy may say."""
    for path in (ROOT / "README.md", ROOT / "deploy" / "helm" / "kube-noob" / "README.md"):
        text = path.read_text(encoding="utf-8")
        assert "restricted-v2" in text, path.name  # otherwise this test passes by the claim being absent
        assert "runs under `restricted-v2`" not in text, path.name
        assert "run under `restricted-v2`" not in text, path.name
        assert "written for `restricted-v2`" in text, path.name
