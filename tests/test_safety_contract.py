def _parse(sc: ModuleType, text: str, values: dict[str, Any] | None = None) -> list[Any]:
    return list(sc.parse_template("t.yaml", text, values if values is not None else {}))


ROLE = "kind: Role\nmetadata:\n  name: {{ $name }}\nrules:\n"


def test_the_template_reader_follows_if_and_else(sc: ModuleType) -> None:
    text = (
        '{{- $name := printf "%s-read" (include "kube-noob.fullname" .) }}\n'
        "{{- if .Values.a.on }}\n" + ROLE + '  - apiGroups: [""]\n    resources: [pods]\n    verbs: [get, list]\n'
        "{{- else }}\n" + ROLE + "  - apiGroups: [apps]\n    resources: [deployments]\n    verbs: [get]\n{{- end }}\n"
    )
    off = _parse(sc, text, {"a": {"on": False}})
    assert [(r.api_groups, r.resources, r.verbs, r.default_install) for r in off] == [
        (("",), ("pods",), ("get", "list"), False),
        (("apps",), ("deployments",), ("get",), True),
    ]
    on = _parse(sc, text, {"a": {"on": True}})
    assert [(r.resources, r.default_install) for r in on] == [(("pods",), True), (("deployments",), False)]
    assert off[0].role == "Role <fullname>-read" and off[0].when == ("a.on",)
    assert off[1].when == ("not (a.on)",)


def test_an_include_binding_decides_which_resources_a_shared_rule_list_has(sc: ModuleType) -> None:
    text = (
        '{{- define "t.rules" -}}\nrules:\n  - apiGroups: [""]\n'
        "    resources: [pods{{ if .cluster }}, nodes{{ end }}]\n    verbs: [get]\n{{- end -}}\n"
        "{{- if .Values.on }}\n"
        '{{- $name := printf "%s-read" (include "kube-noob.fullname" .) }}\n'
        "kind: ClusterRole\nmetadata:\n  name: {{ $name }}\n"
        '{{ include "t.rules" (dict "cluster" true) }}\n---\n'
        "kind: Role\nmetadata:\n  name: {{ $name }}\n"
        '{{ include "t.rules" (dict "cluster" false) }}\n{{- end }}\n'
    )
    got = _parse(sc, text, {"on": False})
    assert [(r.kind, r.resources, r.gates, r.default_install) for r in got] == [
        ("ClusterRole", ("pods", "nodes"), ("on",), False),
        ("Role", ("pods",), ("on",), False),
    ]


def test_the_template_reader_refuses_what_it_cannot_prove(sc: ModuleType) -> None:
    with pytest.raises(sc.ChartError, match="verbs"):  # a rule list in a shape the reader does not know
        _parse(sc, ROLE + "  - apiGroups: [apps]\n    resources:\n      - deployments\n    verbs:\n      - get\n")
    with pytest.raises(sc.ChartError, match="condition"):  # a condition it cannot evaluate
        _parse(
            sc,
            '{{- if semverCompare ">=1.30" .Capabilities.KubeVersion.Version }}\n'
            + ROLE
            + "  - apiGroups: [apps]\n    resources: [deployments]\n    verbs: [get]\n{{- end }}\n",
        )
    with pytest.raises(sc.ChartError, match="cannot settle"):  # an item that depends on a value, not an include
        _parse(sc, ROLE + "  - apiGroups: [apps]\n    resources: [a{{ if .Values.b }}, c{{ end }}]\n    verbs: [get]\n")
    with pytest.raises(sc.ChartError, match="not a Role"):
        _parse(sc, "kind: ConfigMap\nrules:\n  - apiGroups: [apps]\n    resources: [deployments]\n    verbs: [get]\n")


def test_a_dry_run_style_rule_takes_its_resources_from_the_values(sc: ModuleType) -> None:
    text = (
        '{{- $name := printf "%s-dry-run" (include "kube-noob.fullname" .) }}\n{{- if .Values.dryRun.enabled }}\n'
        + ROLE
        + "  {{- range $.Values.dryRun.rules }}\n"
        "  - apiGroups: {{ toJson .apiGroups }}\n    resources: {{ toJson .resources }}\n    verbs: [create, patch]\n"
        "  {{- end }}\n{{- end }}\n"
    )
    values = {
        "dryRun": {
            "enabled": False,
            "rules": [
                {"apiGroups": ["apps"], "resources": ["deployments"]},
                {"apiGroups": [""], "resources": ["services"]},
            ],
        }
    }
    got = _parse(sc, text, values)
    assert [(r.api_groups, r.resources, r.verbs, r.gates) for r in got] == [
        (("apps",), ("deployments",), ("create", "patch"), ("dryRun.enabled",)),
        (("",), ("services",), ("create", "patch"), ("dryRun.enabled",)),
    ]


def _violations(sc: ModuleType, text: str, values: dict[str, Any], configmap: str = "") -> list[str]:
    return sc.chart_violations(_parse(sc, text, values), values, configmap)


def test_chart_violations_flag_every_unsafe_shape(sc: ModuleType) -> None:
    def role(rule: str, gate: str | None = None) -> str:
        body = ROLE + rule
        return (f"{{{{- if .Values.{gate} }}}}\n{body}{{{{- end }}}}\n") if gate else body

    def one(resources: str, verbs: str) -> str:
        return f'  - apiGroups: [""]\n    resources: [{resources}]\n    verbs: [{verbs}]\n'

    wired = "probe:\n  enabled: {{ .Values.probe.enabled }}\n"
    values: dict[str, Any] = {"probe": {"enabled": False}, "other": {"on": False}, "config": {"clusterEnabled": False}}
    assert _violations(sc, role(one("pods", "get, list, watch"), "config.clusterEnabled"), values) == []
    assert _violations(sc, role(one("pods/ephemeralcontainers", "patch"), "probe.enabled"), values, wired) == []
    # a write verb with no gate at all, or behind a read tier's value, or a value that is not a tier
    assert _violations(sc, role(one("pods", "get, delete")), values)
    assert _violations(sc, role(one("pods", "get, delete"), "config.clusterEnabled"), values)
    assert _violations(sc, role(one("pods", "patch"), "other.on"), values)
    # a write tier whose value is on by default, or is not the value the server's tier switch reads
    assert _violations(sc, role(one("pods", "patch"), "probe.enabled"), {**values, "probe": {"enabled": True}}, wired)
    assert _violations(sc, role(one("pods", "patch"), "probe.enabled"), values, "probe:\n  enabled: false\n")
    # secrets (any verb), wildcards, and the four dangerous subresources
    assert _violations(sc, role(one("secrets", "get"), "config.clusterEnabled"), values)
    assert _violations(sc, role(one("pods", "*"), "config.clusterEnabled"), values)
    assert _violations(sc, role(one("*", "get"), "config.clusterEnabled"), values)
    for sub in ("pods/exec", "pods/attach", "pods/portforward", "services/proxy", "nodes/proxy"):
        assert _violations(sc, role(one(sub, "get"), "config.clusterEnabled"), values), sub


def test_role_bindings_to_built_in_roles_are_flagged(sc: ModuleType, tmp_path: Path) -> None:
    def problems(text: str) -> list[str]:
        (tmp_path / "b.yaml").write_text(text, encoding="utf-8")
        return list(sc.role_ref_violations(tmp_path, readable=("b.yaml",)))

    assign = '{{- $name := printf "%s-read" (include "kube-noob.fullname" .) }}\n'
    role = assign + "kind: Role\nmetadata:\n  name: {{ $name }}\n---\n"
    assert problems("kind: RoleBinding\nroleRef: {apiGroup: x, kind: ClusterRole, name: cluster-admin}\n")
    assert problems("kind: RoleBinding\nroleRef:\n  apiGroup: x\n  kind: ClusterRole\n  name: edit\n")
    assert problems(role + "kind: RoleBinding\nroleRef: {apiGroup: x, kind: Role, name: other}\n")
    assert problems(role + "kind: RoleBinding\nroleRef: {apiGroup: x, kind: ClusterRole, name: {{ $name }}}\n")
    assert problems(role + "kind: RoleBinding\nroleRef: {apiGroup: x, kind: Role, name: {{ $name }}}\n") == []
    assert problems(role + "kind: RoleBinding\nroleRef:\n  apiGroup: x\n  kind: Role\n  name: {{ $name }}\n") == []
    (tmp_path / "b.yaml").write_text("kind: RoleBinding\nroleRef: {kind: Role, name: x}\n", encoding="utf-8")
    assert sc.role_ref_violations(tmp_path), "a template with a binding that the contract does not read is flagged"


