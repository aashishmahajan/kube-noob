def test_every_write_verb_in_the_chart_rbac_sits_behind_a_tier_value_that_is_off_by_default(
    sc: ModuleType, rules: list[Any]
) -> None:
    writers = [r for r in rules if set(r.verbs) - READ]
    assert {r.template for r in writers} == {"rbac-tiers.yaml"}, "the probe and dry-run Roles are the only writers"
    assert {g for r in writers for g in r.gates} >= {"probe.enabled", "dryRun.enabled"}
    configmap = (TEMPLATES / "configmap.yaml").read_text(encoding="utf-8")
    write_switches = {s for t in tiers.TIERS if t.writes for s in t.switches}
    for r in writers:
        assert not r.default_install, f"{r.role} is rendered in a default install"
        gates = [g for g in r.gates if g in write_switches]
        assert gates, f"{r.role} is not behind a write tier's value: {r.when}"
        for gate in gates:
            node: Any = VALUES
            for part in gate.split("."):
                node = node[part]
            assert node is False, f"values.yaml turns {gate} on"
            section, key = gate.split(".")
            assert re.search(
                rf"^\s*{section}:\s*\n\s*{key}: \{{\{{ \.Values\.{section}\.{key} \}}\}}", configmap, re.M
            ), f"{gate} must be the same value that turns the tier on in the server's config"
    assert sc.chart_violations(rules, VALUES, configmap) == []


