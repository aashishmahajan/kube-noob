def test_tool_violations_flag_unsafe_tools(sc: ModuleType) -> None:
    def tool(**over: Any) -> Any:
        base = {
            "name": "x",
            "read_only": True,
            "read_only_shared": True,
            "open_world": False,
            "tier": None,
            "local": "default",
            "shared": "default",
        }
        return sc.Tool(**{**base, **over})

    def check(*given: Any, writers: dict[str, str] | None = None) -> list[str]:
        return list(sc.tool_violations(given, writers={} if writers is None else writers))

    assert check(tool()) == []
    assert check(tool(read_only=False)), "a writer without a tier"
    assert check(tool(read_only=False), writers={"x": "its own state"}) == [], "a named local-state writer"
    assert check(tool(), writers={"x": "its own state"}), "an exception for a tool that is read-only is stale"
    assert check(tool(read_only=False, tier="P")) == []
    assert check(tool(read_only=False, tier="Z")), "an unknown tier"
    assert check(tool(open_world=True)), "an open-world tool offered by default"
    assert check(tool(open_world=True, local="needs cluster.enabled", shared="needs cluster.enabled")) == []


