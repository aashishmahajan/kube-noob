"""The safety contract (docs/safety-contract.md) is generated from the code; the invariants it states fail the build.

Evaluators ask every MCP server to prove it is read-only. ``scripts/safety_contract.py`` derives the proof from the
code (tool specs, the cluster backend, the Helm chart's RBAC, the config defaults, every subprocess call site, the
sanitiser) and these tests make each claim a failing test when it stops being true. The negative tests feed the
checks deliberately unsafe input, so a check that quietly accepts everything cannot pass.
"""

