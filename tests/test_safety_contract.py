VALUES = yaml.safe_load((ROOT / "deploy" / "helm" / "kube-noob" / "values.yaml").read_text(encoding="utf-8"))
READ = {"get", "list", "watch"}


def _load() -> ModuleType:
    spec = importlib.util.spec_from_file_location("safety_contract", ROOT / "scripts" / "safety_contract.py")
    assert spec and spec.loader
    mod = importlib.util.module_from_spec(spec)
    sys.modules["safety_contract"] = mod
    spec.loader.exec_module(mod)
    return mod


@pytest.fixture(scope="module")
def sc() -> ModuleType:
    return _load()


