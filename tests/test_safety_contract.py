def _every_tool_the_toolkit_can_offer() -> set[str]:
    """Independent of the script: switch everything on and ask the Toolkit, for both a local and a shared server."""
    import tempfile

    from kube_noob.config import Settings
    from kube_noob.toolkit import Toolkit

    names: set[str] = set()
    with tempfile.TemporaryDirectory() as data:
        every = {
            "dataDir": data,
            "webEnabled": True,
            "cluster": {"enabled": True},
            "rhacs": {"enabled": True, "endpoint": "https://central.example.svc"},
            "memory": {"paths": [data]},
            "mustGather": {"allowedDir": data},
            "probe": {"enabled": True},
            "dryRun": {"enabled": True},
            "itsm": {"writeEnabled": True},
            "notify": {"enabled": True},
            "gate": {"enabled": True},
            "admission": {"enforce": ["KN-S001"]},
        }
        for shared in (False, True):
            names |= {t.name for t in Toolkit(Settings.model_validate(every), shared=shared).specs()}
    return names


def test_every_tool_is_in_the_contract(tools: list[Any]) -> None:
    expected = _every_tool_the_toolkit_can_offer()
    assert {t.name for t in tools} == expected
    text = DOC.read_text(encoding="utf-8")
    for name in sorted(expected):
        assert re.search(rf"^\| `{re.escape(name)}` \|", text, re.MULTILINE), name


