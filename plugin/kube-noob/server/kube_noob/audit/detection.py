"""What a cluster's audit configuration can and cannot record (R4, G244; corrected by G249).

Eleven `AUD-*` checks were proposed in the external reviews -- are logs forwarded, is retention long enough,
does anyone review them, is the SIEM healthy -- and every one needs a system kube-noob has no credentials for.
A rule that answers "not evaluated" eleven times is coverage theatre. This module answers the part that IS
decidable from a read-only bundle, and says plainly what it cannot answer.

It is a projection, not a rule: it reads the same cluster-scoped `APIServer` singleton `KN-S035` reads
(`config.openshift.io`), and turns `spec.audit` into a statement about categories of API activity. No event, no
request body, nothing about a person is read -- only the configuration.

**Where the facts come from, and why not from the API documentation.** The first version of this module quoted
the field documentation of `Audit` in openshift/api, which says `Default` is "MetaData level logging with the
exception of events (not logged at all)". That is the API contract, and it is simplified and, on this point,
stale: the policy a cluster actually runs is generated by `cluster-kube-apiserver-operator` from the manifests
in `github.com/openshift/library-go` (`pkg/operator/apiserver/audit/manifests`), and the rule that dropped
events lived in `base-policy.yaml` through release-4.17 and is **gone from release-4.18 onwards**. So from
OpenShift 4.18 an Event IS recorded, and a statement built on the API comment told a reader that a deleted
Event left no trace in a cluster whose audit log has it -- an understatement in the direction that matters most
for incident response. Every row below is read from those manifests, with the branch named, and the one row
that changed between releases is decided by the cluster's version or reported as undecidable without it.

The manifests, read 2026-11-06 (release-4.17, release-4.18, release-4.20 and master):

* `base-policy.yaml` -- `omitStages: [RequestReceived]`; nothing logged for the authenticated and
  unauthenticated discovery and health endpoints (`/api*`, `/version`, `/healthz`, `/readyz`, `/livez`) or for
  `system:apiserver` reading `apirequestcounts`; **through 4.17 only**, nothing logged for core `events`.
* `none-rules.yaml` -- a single `level: None`: nothing at all.
* `default-rules.yaml` -- `RequestResponse` for create, update, patch and delete of `identities`,
  `oauthaccesstokens` and `oauthauthorizetokens`; `Metadata` for everything else.
* `writerequestbodies-rules.yaml` -- `Metadata` only (never a body) for `secrets`,
  `serviceaccounts/token`, `routes`, `routes/status`, `tokenreviews`, `tokenrequests`, `oauthclients` and
  `machineconfig`/`controllerconfig`, under the comment "exclude resources where the body is
  security-sensitive"; then `RequestResponse` for update, patch, create, delete and deletecollection;
  `Metadata` for the rest.
* `allrequestbodies-rules.yaml` -- the same security-sensitive exclusion, then `RequestResponse` for
  everything.
* `spec.audit.profile` defaults to `Default` (`+kubebuilder:default=Default` in openshift/api), and
  `customRules` are per group, evaluated top to bottom, first match wins, taking precedence over the top-level
  profile.

Four decisions worth stating, because each is a defect taken the other way.

**An unknown profile is `unknown`, never `no` and never `yes`.** The field is a validated enum on a live
cluster, but a bundle is a file and can carry anything, including a profile a later OpenShift adds.

**A row whose answer changed between releases is undecidable without the version.** `kube-noob audit --version
4.20` decides the events row; without `--version` it says which release changed it rather than picking.

**No object, or a malformed one, means no statement.** On OpenShift the singleton always exists, so its absence
from a bundle means it was not collected; a `spec` or `spec.audit` that is not a mapping is not a configuration
this module can read, and saying "unset, so the default" of it would be a verdict taken from nothing. The block
is also absent off OpenShift, where the resource does not exist -- `KN-S035` declines there for the same
reason, and one report must not both ignore an object and draw an AU-2 conclusion from it.

**One singleton, or none.** A bundle carrying two `config.openshift.io` APIServer objects does not say which
one the cluster has, so the statement is undecided and both are named: reading the first and mentioning the
second in a field the text renderer did not print was a verdict that flipped with document order.
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass
from typing import Any, Literal

from kube_noob.audit.rules import APISERVER_GROUP, AUDIT_PROFILE_NONE
from kube_noob.catalog import parse_minor
from kube_noob.yamlio import Document

#: The profiles openshift/api defines, in order of how much each records. A value outside this set is reported
#: as undecidable rather than guessed.
PROFILES: tuple[str, ...] = ("None", "Default", "WriteRequestBodies", "AllRequestBodies")

#: The default when `spec.audit.profile` is unset (`+kubebuilder:default=Default`).
DEFAULT_PROFILE = "Default"

#: The release that stopped dropping core `events` from the audit policy: the `level: None` rule for them is in
#: library-go's `base-policy.yaml` through release-4.17 and absent from release-4.18 on.
EVENTS_RECORDED_FROM = (4, 18)

#: Where every row above comes from, named in the output so a reader can check it rather than trust it.
SOURCE = (
    "github.com/openshift/library-go pkg/operator/apiserver/audit/manifests, the policy "
    "cluster-kube-apiserver-operator generates (read 2026-11-06)"
)

Recorded = Literal["yes", "no", "unknown"]


@dataclass(frozen=True)
class Category:
    """One category of API activity, and the profiles that record it.

    `yes_for` is read as "recorded under exactly these profiles"; under any other profile, not at all.
    `from_minor` marks a row whose answer changed between OpenShift releases: recorded from that minor, not
    before, and undecidable when the cluster's version is not known.
    """

    id: str
    what: str
    yes_for: tuple[str, ...]
    because: str
    from_minor: tuple[int, int] | None = None


CATEGORIES: tuple[Category, ...] = (
    Category(
        "request-metadata",
        "who made each request, when, with which verb, against which resource, and how the API server answered",
        ("Default", "WriteRequestBodies", "AllRequestBodies"),
        "every profile but None ends in a catch-all Metadata rule; the discovery and health endpoints "
        "(/api*, /version, /healthz, /readyz, /livez) and the API server's own reads of apirequestcounts are "
        "the exceptions, in base-policy.yaml",
    ),
    Category(
        "write-bodies",
        "what a create, update, patch, delete or deletecollection contained, and what the API server returned",
        ("WriteRequestBodies", "AllRequestBodies"),
        "writerequestbodies-rules.yaml logs RequestResponse for those verbs; Default does not",
    ),
    Category(
        "read-bodies",
        "what a get or list returned, so what an exfiltrating reader actually saw",
        ("AllRequestBodies",),
        "only allrequestbodies-rules.yaml ends in a RequestResponse catch-all",
    ),
    Category(
        "sensitive-bodies",
        "what a Secret, a ServiceAccount token, a Route, a token review, an OAuthClient or a MachineConfig contained",
        (),
        "both body profiles put those resources at Metadata first, under the comment 'exclude resources where "
        "the body is security-sensitive', so no profile records their contents",
    ),
    Category(
        "oauth-token-bodies",
        "the body and the response of a write to oauthaccesstokens, oauthauthorizetokens or identities, which "
        "is how a token grant is traced",
        ("Default", "WriteRequestBodies", "AllRequestBodies"),
        "default-rules.yaml logs RequestResponse for create, update, patch and delete of those three, and the "
        "body profiles record every write; None records nothing",
    ),
    Category(
        "events",
        "API activity on core Event objects, including a deletion that removes the trace of an incident",
        ("Default", "WriteRequestBodies", "AllRequestBodies"),
        "base-policy.yaml dropped core events through release-4.17 and stopped from release-4.18, so this row "
        "is about the cluster's version as much as its profile",
        from_minor=EVENTS_RECORDED_FROM,
    ),
)

#: What no reading of this object can establish. Printed every time, because a coverage statement that lists
#: only what it knows reads as a complete answer. None of these is reachable without a credential for another
#: system, which is why the eleven proposed checks were refused rather than stubbed (docs/ideation-review.md).
CANNOT_SAY: tuple[str, ...] = (
    "whether these records leave the cluster or reach a SIEM: the forwarding configuration is not in this "
    "object, and kube-noob has no credentials for the collector",
    "how long they are kept, or whether they survive a node replacement",
    "whether anyone reads them, or whether an alert fires on one (AU-6 is about review, not generation)",
    "anything that is not an API request to the OpenShift-provided API servers: the kubelet, etcd, a node "
    "shell and a process inside a container are all outside this policy",
    "whether an administrator has replaced the generated policy by other means; this is what the APIServer "
    "object asks for, read against the manifests the operator generates it from",
)


def _records(profile: str, cat: Category, minor: tuple[int, int] | None) -> Recorded:
    if profile not in PROFILES:
        return "unknown"
    if profile not in cat.yes_for:
        return "no"
    if cat.from_minor is None:
        return "yes"
    if minor is None:
        return "unknown"
    return "yes" if minor >= cat.from_minor else "no"


def _statement(profile: str, minor: tuple[int, int] | None) -> list[dict[str, str]]:
    return [
        {"id": c.id, "what": c.what, "recorded": _records(profile, c, minor), "because": c.because} for c in CATEGORIES
    ]


def _events_clause(profile: str, minor: tuple[int, int] | None) -> str:
    """The events half of the sentence, which is the half that depends on the release."""
    if profile == AUDIT_PROFILE_NONE or profile not in PROFILES:
        return ""
    from_version = f"{EVENTS_RECORDED_FROM[0]}.{EVENTS_RECORDED_FROM[1]}"
    if minor is None:
        return (
            f", and whether API activity on Event objects is recorded depends on a version this bundle does "
            f"not state: it is dropped before {from_version} and recorded from {from_version}"
        )
    if minor >= EVENTS_RECORDED_FROM:
        return ", and API activity on Event objects is recorded too"
    return f", and API activity on Event objects is not recorded at all before {from_version}"


def _sentence(
    profile: str,
    assumed: bool,
    minor: tuple[int, int] | None = None,
    group: str | None = None,
    overrides: Sequence[str] = (),
) -> str:
    """The one honest sentence the roadmap item asked for, for the cluster or for one group."""
    whose = "requests" if group is None else f"requests from {group}"
    for_every = "every request" if group is None else f"every request from {group}"
    # A top-level sentence that ignores a customRules entry is wrong twice over: it claims coverage for a
    # group that has none, and it claims none for a group that has more than the cluster (G249).
    tail = ""
    if overrides:
        shown = ", ".join(overrides[:3])
        if len(overrides) > 3:
            shown += f" and {len(overrides) - 3} more"
        tail = f" It does not describe {shown}, which customRules gives its own profile."
    if profile not in PROFILES:
        where = f"customRules entry for {group}" if group else "spec.audit.profile"
        return (
            f"The {where} is {profile!r}, which is not a profile this build knows "
            f"({', '.join(PROFILES)}), so what is recorded for {whose} cannot be stated from it.{tail}"
        )
    if profile == AUDIT_PROFILE_NONE:
        scope = f"No request from {group} is recorded" if group else "No API request is recorded"
        for_what = (
            f"there is no audit evidence for what anyone in {group} does"
            if group
            else "there is no audit evidence for anything that happens on this cluster"
        )
        return f"{scope} at all, not even an OAuth token grant, so {for_what}.{tail}"
    where = f"profile {profile}" + (" (unset, so the API server's default)" if assumed else "")
    bodies = {
        "Default": "what a request contained is not recorded, except a write to an OAuth token or identity",
        "WriteRequestBodies": (
            "what a create, update, patch or delete contained is recorded, except for Secrets, ServiceAccount "
            "tokens, Routes, token reviews, OAuthClients and MachineConfig, whose bodies no profile records"
        ),
        "AllRequestBodies": (
            "what every request contained and returned is recorded as well, except for Secrets, ServiceAccount "
            "tokens, Routes, token reviews, OAuthClients and MachineConfig, whose bodies no profile records"
        ),
    }[profile]
    return (
        f"Under {where}, who did what to which object is recorded for {for_every} but the discovery and health "
        f"endpoints, {bodies}{_events_clause(profile, minor)}.{tail}"
    )


def _undecided(refs: list[str], why: str) -> dict[str, Any]:
    """A block that states what it cannot read, rather than a verdict taken from it."""
    return {
        "from": refs,
        "undecided": why,
        "controls": ["AU-2", "AU-12"],
        "source": SOURCE,
        "cannotSay": list(CANNOT_SAY),
    }


def coverage(docs: Sequence[Document], version: str | None = None) -> dict[str, Any] | None:
    """A detection-coverage statement from the cluster audit configuration, or None when it was not collected.

    Only the `config.openshift.io` APIServer is read: an `APIServer` kind in another group is a different
    resource that happens to share a name. `version` is the cluster's OpenShift version, which one row depends
    on; without it that row is reported as undecidable rather than guessed.
    """
    found = [d for d in docs if d.kind == "APIServer" and d.api_version.split("/", 1)[0] == APISERVER_GROUP]
    if not found:
        return None
    refs = [d.ref() for d in found]
    named = [d for d in found if (d.data.get("metadata") or {}).get("name") == "cluster"] if len(found) > 1 else found
    if len(named) != 1:
        return _undecided(
            refs,
            "this bundle carries several cluster-scoped APIServer objects and none of them is the singleton "
            "named 'cluster', so which configuration the cluster has cannot be read from it",
        )
    doc = named[0]
    spec = doc.data.get("spec") if isinstance(doc.data, dict) else None
    if spec is not None and not isinstance(spec, dict):
        return _undecided(refs, "spec is not a mapping, so this object states no audit configuration")
    audit = spec.get("audit") if isinstance(spec, dict) else None
    if audit is not None and not isinstance(audit, dict):
        return _undecided(refs, "spec.audit is not a mapping, so this object states no audit configuration")
    audit = audit if isinstance(audit, dict) else {}
    minor = parse_minor(version) if version else None
    raw = audit.get("profile")
    assumed = raw is None or raw == ""
    profile = DEFAULT_PROFILE if assumed else str(raw)
    groups: list[dict[str, Any]] = []
    rules = audit.get("customRules")
    for i, entry in enumerate(rules if isinstance(rules, list) else []):
        if not isinstance(entry, dict):
            continue
        g_raw = entry.get("profile")
        g_profile = DEFAULT_PROFILE if g_raw is None or g_raw == "" else str(g_raw)
        g_name = str(entry.get("group") or "(unnamed group)")
        groups.append(
            {
                "group": g_name,
                "precedence": i,
                "profile": g_profile,
                "statement": _sentence(g_profile, g_raw is None or g_raw == "", minor, g_name),
                "records": _statement(g_profile, minor),
            }
        )
    out: dict[str, Any] = {
        "from": doc.ref(),
        "profile": profile,
        "profileAssumed": assumed,
        "platformVersion": version,
        "statement": _sentence(profile, assumed, minor, None, [g["group"] for g in groups]),
        "records": _statement(profile, minor),
        "controls": ["AU-2", "AU-12"],
        "source": SOURCE,
        "cannotSay": list(CANNOT_SAY),
    }
    if groups:
        out["groups"] = groups
        # Precedence is a fact about the list, not about any one entry, and it is the part a reader gets wrong:
        # a user in two of these groups is covered by whichever entry is listed first, not by the stricter one.
        out["cannotSay"] = [
            *out["cannotSay"],
            "which entry applies to a user in several of these groups beyond the order they are listed in: "
            "the first match applies, and group membership is not in this object",
        ]
    if version is None:
        out["cannotSay"] = [
            *out["cannotSay"],
            f"whether API activity on Event objects is recorded: that changed in OpenShift "
            f"{EVENTS_RECORDED_FROM[0]}.{EVENTS_RECORDED_FROM[1]} and this bundle does not state a version "
            f"(pass --version)",
        ]
    return out


def render_text(cov: dict[str, Any]) -> str:
    """The block `kube-noob audit --format text` prints. Short on purpose: the detail is in the JSON."""
    where = cov["from"] if isinstance(cov["from"], str) else ", ".join(cov["from"])
    if "undecided" in cov:
        lines = [f"Detection coverage (from {where}): not decided", "", f"  {cov['undecided']}", ""]
        lines.append("  This says nothing about:")
        lines.extend(f"    - {w}" for w in cov["cannotSay"])
        return "\n".join(lines) + "\n"
    version = f", version {cov['platformVersion']}" if cov.get("platformVersion") else ""
    lines = [f"Detection coverage (from {where}, spec.audit.profile: {cov['profile']}{version})", ""]
    lines.append(f"  {cov['statement']}")
    lines.append("")
    mark = {"yes": "recorded", "no": "NOT recorded", "unknown": "cannot say"}
    for row in cov["records"]:
        lines.append(f"  {mark[row['recorded']]:>12}: {row['what']}")
    for g in cov.get("groups", ()):
        lines.append("")
        lines.append(f"  group {g['group']} (customRules[{g['precedence']}], profile {g['profile']}) overrides it:")
        lines.append(f"    {g['statement']}")
    lines.append("")
    lines.append(f"  Read against {cov['source']}.")
    lines.append("  This says nothing about:")
    lines.extend(f"    - {w}" for w in cov["cannotSay"])
    return "\n".join(lines) + "\n"
