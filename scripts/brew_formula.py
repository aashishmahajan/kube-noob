#!/usr/bin/env python3
"""Write the Homebrew formula (Formula/kube-noob.rb) for a kube-noob release that is already on PyPI.

Usage:
  python scripts/brew_formula.py [VERSION]           print the formula (default: the version in src/kube_noob)
  python scripts/brew_formula.py VERSION --write     write Formula/kube-noob.rb
  python scripts/brew_formula.py --check             exit 1 if Formula/kube-noob.rb does not match PyPI for its version

The formula installs the release wheel into a private virtualenv with every dependency pinned by hash from the
requirements.lock inside the release sdist (`pip --require-hashes --only-binary=:all:`), so nothing is compiled and
nothing unpinned is fetched. Users install it with:
  brew tap aashishmahajan/kube-noob https://github.com/aashishmahajan/kube-noob
  brew install aashishmahajan/kube-noob/kube-noob
"""

from __future__ import annotations

import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FORMULA = ROOT / "Formula" / "kube-noob.rb"
PYTHON_FORMULA = "python@3.13"
_SEMVER = re.compile(r"^\d+\.\d+\.\d+$")

TEMPLATE = """\
# Generated by scripts/brew_formula.py from the PyPI release files. Do not edit by hand.
class KubeNoob < Formula
  desc "Kubernetes, OpenShift, ROSA HCP, Helm and RHACS audit, debugging and learning tools"
  homepage "https://github.com/aashishmahajan/kube-noob"
  url "{sdist_url}"
  sha256 "{sdist_sha256}"
  license "Apache-2.0"

  depends_on "{python}"

  resource "wheel" do
    url "{wheel_url}"
    sha256 "{wheel_sha256}"
  end

  def install
    python = Formula["{python}"].opt_libexec/"bin/python"
    system python, "-m", "venv", libexec
    pip = [libexec/"bin/python", "-m", "pip", "--disable-pip-version-check", "--no-input", "install"]
    # Every dependency at the version and hash pinned in the release's requirements.lock; wheels only.
    system(*pip, "--require-hashes", "--only-binary=:all:", "--no-deps", "-r", buildpath/"requirements.lock")
    wheel = buildpath/"kube_noob-#{{version}}-py3-none-any.whl"
    cp resource("wheel").cached_download, wheel
    system(*pip, "--no-deps", "--no-index", wheel)
    bin.install_symlink libexec/"bin/kube-noob"
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/kube-noob --version")
    (testpath/"deploy.yaml").write <<~YAML
      apiVersion: apps/v1
      kind: Deployment
      metadata:
        name: api
      spec:
        selector:
          matchLabels:
            app: api
        template:
          metadata:
            labels:
              app: api
          spec:
            containers:
              - name: api
                image: quay.io/example/api:latest
                securityContext:
                  privileged: true
    YAML
    audit = shell_output("#{{bin}}/kube-noob audit -f #{{testpath}}/deploy.yaml --platform openshift --format json")
    assert_match "\\"score\\"", audit
    (testpath/"events.txt").write "Last State: Terminated\\nReason: OOMKilled\\nExit Code: 137\\n"
    assert_match "DBG-OOM", shell_output("#{{bin}}/kube-noob diagnose -f #{{testpath}}/events.txt --format json")
  end
end
"""


def _current_version() -> str:
    m = re.search(r'__version__ = "([^"]+)"', (ROOT / "src/kube_noob/__init__.py").read_text())
    if not m:
        raise SystemExit("cannot find __version__")
    return m.group(1)


def release_files(version: str) -> dict[str, str]:
    """The sdist and the py3-none-any wheel of a PyPI release, with their sha256 digests."""
    if not _SEMVER.match(version):
        raise SystemExit(f"{version!r} is not MAJOR.MINOR.PATCH")
    url = f"https://pypi.org/pypi/kube-noob/{version}/json"
    with urllib.request.urlopen(url, timeout=30) as resp:
        data = json.load(resp)
    files: dict[str, str] = {}
    for f in data["urls"]:
        if f["packagetype"] == "sdist":
            files["sdist_url"], files["sdist_sha256"] = f["url"], f["digests"]["sha256"]
        elif f["filename"] == f"kube_noob-{version}-py3-none-any.whl":
            files["wheel_url"], files["wheel_sha256"] = f["url"], f["digests"]["sha256"]
    if set(files) != {"sdist_url", "sdist_sha256", "wheel_url", "wheel_sha256"}:
        raise SystemExit(f"kube-noob {version} on PyPI lacks an sdist or a py3-none-any wheel: {sorted(files)}")
    return files


def render(version: str) -> str:
    return TEMPLATE.format(python=PYTHON_FORMULA, **release_files(version))


def formula_version(text: str) -> str:
    m = re.search(r"/kube_noob-(\d+\.\d+\.\d+)\.tar\.gz\"", text)
    if not m:
        raise SystemExit("Formula/kube-noob.rb has no kube_noob-<version>.tar.gz url")
    return m.group(1)


def main(argv: list[str]) -> int:
    if argv == ["--check"]:
        text = FORMULA.read_text()
        version = formula_version(text)
        if text != render(version):
            print(f"Formula/kube-noob.rb does not match PyPI kube-noob {version}", file=sys.stderr)
            return 1
        print(f"Formula/kube-noob.rb matches PyPI kube-noob {version}")
        return 0
    write = "--write" in argv
    rest = [a for a in argv if a != "--write"]
    if len(rest) > 1 or any(a.startswith("-") for a in rest):
        print(__doc__)
        return 2
    text = render(rest[0] if rest else _current_version())
    if write:
        FORMULA.parent.mkdir(exist_ok=True)
        FORMULA.write_text(text)
        print(f"wrote {FORMULA.relative_to(ROOT)}")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
