"""Generate the FedRAMP 20x KSI crosswalk from the vendored dataset.

Two artefacts, both generated, neither to be edited by hand:

* the region between the markers in ``src/kube_noob/audit/fedramp.py`` -- the indicators, their families, the
  control ids each one cites, and the inversion onto kube-noob's own controls;
* ``docs/fedramp-ksi.md`` in full, from that module.

The previous version of this work was hand-maintained against a file that no longer exists: a separate
``FRMR.KSI.key-security-indicators.json`` at 25.11C, eleven families, indicators keyed by number, seven of them
recorded as retired. Every one of those facts was wrong by 2026-11-02 and the document went on asserting them.
Generating is the only way a crosswalk onto someone else's register stays true.

``--refresh`` re-fetches the upstream file (the only step that needs the network), checks it against the recorded
hash, and rewrites the vendored extract when it has moved. Everything else is offline.
"""

from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from kube_noob.audit.controls import TITLES  # noqa: E402
from kube_noob.oscal import control_id  # noqa: E402

VENDOR = ROOT / "vendor/fedramp/fedramp-ksi.json"
MODULE = ROOT / "src/kube_noob/audit/fedramp.py"
DOC = ROOT / "docs/fedramp-ksi.md"
UPSTREAM = "https://raw.githubusercontent.com/FedRAMP/rules/main/fedramp-consolidated-rules.json"
BEGIN = "# --- BEGIN GENERATED by scripts/fedramp_ksi.py from vendor/fedramp/fedramp-ksi.json ---"
END = "# --- END GENERATED ---"
_REGION = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.DOTALL)
_OPTIONAL = "**Optional:**"


def _vendored() -> dict[str, Any]:
    return json.loads(VENDOR.read_text(encoding="utf-8"))  # type: ignore[no-any-return]


def _extract_text(ksi: dict[str, Any]) -> str:
    return json.dumps(ksi, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def indicators(ksi: dict[str, Any]) -> dict[str, dict[str, Any]]:
    """Every indicator, keyed by the mnemonic the dataset itself keys it by (``KSI-CED-RAT``)."""
    out: dict[str, dict[str, Any]] = {}
    for fam in sorted(ksi, key=lambda k: str(ksi[k]["id"])):
        body = ksi[fam]
        for ind in sorted(body["indicators"]):
            entry = body["indicators"][ind]
            varies = entry.get("varies_by_class") or {}
            out[ind] = {
                "family": body["short_name"],
                "name": entry["name"],
                "controls": tuple(entry["controls"]),
                "variesByClass": tuple(sorted(varies)),
                "optionalFor": tuple(
                    sorted(k for k, v in varies.items() if str(v.get("statement", "")).startswith(_OPTIONAL))
                ),
            }
    return out


def by_control(inds: dict[str, dict[str, Any]]) -> dict[str, tuple[str, ...]]:
    """kube-noob's controls -> the indicators citing them. Every control is a key, including the ones nothing
    cites: a crosswalk that lists only what matched reads as full coverage."""
    cited: dict[str, set[str]] = {}
    for ind, body in inds.items():
        for c in body["controls"]:
            cited.setdefault(str(c), set()).add(ind)
    return {c: tuple(sorted(cited.get(control_id(c), ()))) for c in sorted(TITLES)}


def _py(value: Any) -> str:
    if isinstance(value, tuple):
        if not value:
            return "()"
        inner = ", ".join(f'"{v}"' for v in value)
        return f"({inner},)" if len(value) == 1 else f"({inner})"
    return json.dumps(value)


def region(doc: dict[str, Any]) -> str:
    src, ksi = doc["source"], doc["KSI"]
    inds = indicators(ksi)
    mapping = by_control(inds)
    unmapped = tuple(c for c in sorted(TITLES) if not mapping[c])
    lines = [
        BEGIN,
        f'DATASET = "{src["name"]}"',
        f'DATASET_REPO = "{src["repository"]}"',
        f'DATASET_FILE = "{src["url"]}"',
        f'DATASET_VERSION = "{src["version"]}"',
        f'DATASET_UPDATED = "{src["last_updated"]}"',
        f'DATASET_SHA256 = "{src["sha256"]}"',
        f'EXTRACT_SHA256 = "{src["extract_sha256"]}"',
        f'RETRIEVED = "{src["retrieved"]}"',
        "",
        "FAMILIES: dict[str, str] = {",
    ]
    fams = {ksi[k]["short_name"]: ksi[k]["name"] for k in ksi}
    lines += [f'    "{short}": "{fams[short]}",' for short in sorted(fams)]
    lines += ["}", "", "INDICATORS: dict[str, dict[str, Any]] = {"]
    for ind, body in inds.items():
        lines.append(f'    "{ind}": {{')
        lines.append(f'        "family": "{body["family"]}",')
        lines.append(f'        "name": {json.dumps(body["name"])},')
        lines.append(f'        "controls": {_py(body["controls"])},')
        lines.append(f'        "variesByClass": {_py(body["variesByClass"])},')
        lines.append(f'        "optionalFor": {_py(body["optionalFor"])},')
        lines.append("    },")
    lines += ["}", "", "BY_CONTROL: dict[str, tuple[str, ...]] = {"]
    lines += [f'    "{c}": {_py(mapping[c])},' for c in mapping]
    lines += ["}", "", f"UNMAPPED_CONTROLS: tuple[str, ...] = {_py(unmapped)}", END]
    return "\n".join(lines)


def _ruff_formatted(text: str) -> str:
    """Hand the generated module to ``ruff format``, because the committed file is formatted and a generator
    whose output the formatter then rewrites is a generator whose ``--check`` can never pass. (It cannot: an
    indicator citing nineteen controls is one tuple over the 120-column limit, and ruff explodes it.)"""
    ruff = shutil.which("ruff")
    if not ruff:
        raise SystemExit("ruff is not on PATH; install the dev extra (pip install -e '.[dev]')")
    r = subprocess.run(
        [ruff, "format", "--stdin-filename", str(MODULE), "-"],
        input=text,
        capture_output=True,
        text=True,
        check=False,
    )
    if r.returncode != 0:
        raise SystemExit(f"ruff format failed on the generated module: {r.stderr.strip() or r.returncode}")
    return r.stdout


def module_text(doc: dict[str, Any]) -> str:
    current = MODULE.read_text(encoding="utf-8")
    if not _REGION.search(current):
        raise SystemExit(f"{MODULE} has no generated region; refusing to rewrite the whole file")
    return _ruff_formatted(_REGION.sub(lambda _: region(doc), current, count=1))


def doc_text(doc: dict[str, Any]) -> str:
    from kube_noob.audit import fedramp

    inds = fedramp.INDICATORS
    src = doc["source"]
    mapped = [c for c in sorted(TITLES) if fedramp.BY_CONTROL[c]]
    unevidenced = [i for i in sorted(inds) if not fedramp.indicator_rules(i)]
    out = [
        "# FedRAMP 20x Key Security Indicators: what kube-noob's findings are evidence for",
        "",
        "<!-- Generated by scripts/fedramp_ksi.py. Do not edit: run the script. -->",
        "",
        f"Dataset: **{src['name']}** version **{src['version']}** (`last_updated` {src['last_updated']}), the "
        f"KSI section of [`fedramp-consolidated-rules.json`]({src['url']}) in "
        f"[FedRAMP/rules]({src['repository']}), retrieved {src['retrieved']}. The vendored extract is "
        f"`vendor/fedramp/fedramp-ksi.json`; its sha256 is `{src['extract_sha256']}` and the upstream file's is "
        f"`{src['sha256']}`, both asserted by `tests/test_fedramp_ksi.py`.",
        "",
        f"{fedramp.NOT_A_COMPLIANCE_CLAIM}",
        "",
        f"{fedramp.APPLICABILITY}",
        "",
        f"{fedramp.SHARED_CONTROL_IS_NOT_SHARED_SUBJECT}",
        "",
        f"## Coverage: {len(mapped)} of kube-noob's {len(TITLES)} controls are cited by an indicator",
        "",
        f"{len(fedramp.UNMAPPED_CONTROLS)} are cited by none, so no finding of kube-noob's is evidence for any "
        "indicator through them: " + ", ".join(f"**{c}** ({TITLES[c]})" for c in fedramp.UNMAPPED_CONTROLS) + ".",
        "",
        f"In the other direction, {len(unevidenced)} of the {len(inds)} indicators have no kube-noob rule behind "
        "them at all. Those rows carry `evidenced: false` and no counts: a zero in a findings column reads as a "
        "pass, and an indicator kube-noob cannot see has not passed anything. They are "
        + ", ".join(f"`{i}`" for i in unevidenced)
        + ".",
        "",
        f"## The {len(fedramp.EVIDENCE)} indicators a kube-noob finding speaks to directly",
        "",
        "One line each on what the evidence shows and, more importantly, what it does not. An indicator is a "
        "statement about an organisation's practice; kube-noob reads configuration. The gap is not a detail.",
        "",
    ]
    from kube_noob.audit.rules import RULES

    rule_list = list(RULES.values() if isinstance(RULES, dict) else RULES)
    titles = {r.rule_id: r.title for r in rule_list}
    for ind in sorted(fedramp.EVIDENCE):
        body = inds[ind]
        ev = fedramp.EVIDENCE[ind]
        rules = fedramp.indicator_rules(ind)
        out += [
            f"### {ind} — {body['name']} ({fedramp.FAMILIES[body['family']]})",
            "",
        ]
        if not ev["onSubject"]:
            out += [
                "> **These rules reach this indicator only through a shared control.** Read the row as a "
                "warning, not as evidence.",
                "",
            ]
        out += [
            f"- **Shows:** {ev['shows']}",
            f"- **Does not show:** {ev['doesNotShow']}",
            f"- kube-noob controls: {', '.join(fedramp.controls_for(ind)) or 'none'}",
            f"- Rules that are evidence ({len(rules)}), of which the sentences above name "
            f"{len(ev['rules'])}: {', '.join(f'`{r}`' for r in rules[:12])}"
            + (f" and {len(rules) - 12} more" if len(rules) > 12 else ""),
            "",
            "| Rule named above | Its own title, so the sentence can be checked against it |",
            "|---|---|",
        ]
        out += [f"| `{r}` | {titles.get(r, 'NOT IN THE CATALOGUE')} |" for r in ev["rules"]]
        if body["variesByClass"]:
            out.append(
                "- Varies by service class: "
                + ", ".join(sorted(body["variesByClass"]))
                + (
                    "; optional for " + ", ".join(body["optionalFor"])
                    if body["optionalFor"]
                    else "; no class lists it as optional"
                )
            )
        out.append("")
    out += [
        f"## All {len(inds)} indicators, and the kube-noob controls each cites",
        "",
        "| Indicator | Family | Name | kube-noob controls | Varies by class |",
        "|---|---|---|---|---|",
    ]
    for ind in sorted(inds):
        body = inds[ind]
        kn = fedramp.controls_for(ind)
        varies = ", ".join(sorted(body["variesByClass"])) or "no"
        out.append(f"| {ind} | {body['family']} | {body['name']} | {', '.join(kn) or '—'} | {varies} |")
    out.append("")
    return "\n".join(out)


def refresh() -> int:
    import urllib.request

    with urllib.request.urlopen(UPSTREAM, timeout=60) as r:
        raw = r.read()
    digest = hashlib.sha256(raw).hexdigest()
    upstream = json.loads(raw)
    doc = _vendored()
    ksi = upstream["KSI"]
    today = dt.datetime.now(dt.UTC).date().isoformat()
    if digest == doc["source"]["sha256"]:
        # Not "nothing to do": the upstream file matching its recorded hash says nothing about whether the
        # VENDORED extract still equals upstream's KSI section. A tampered extract with a recomputed
        # extract_sha256 passes --check, and this was the one place that could notice.
        if _extract_text(ksi) != _extract_text(doc["KSI"]):
            print(
                "upstream is unchanged but the vendored extract does not match its KSI section; the vendored "
                "file has been edited. Re-vendoring from upstream.",
                file=sys.stderr,
            )
        else:
            print(f"upstream unchanged ({doc['source']['version']}, sha256 {digest[:12]}, checked {today})")
            return 0
    doc = {
        "source": {
            **doc["source"],
            "name": upstream["info"]["title"],
            "version": upstream["info"]["version"],
            "last_updated": upstream["info"]["last_updated"],
            "sha256": digest,
            "bytes": len(raw),
            # Not carried over from the previous vendoring: the old date would then assert a retrieval that did
            # not happen, in the module, in every `ksi` run and in the generated document.
            "retrieved": today,
            "extract_sha256": hashlib.sha256(_extract_text(ksi).encode()).hexdigest(),
        },
        "KSI": ksi,
    }
    VENDOR.write_text(json.dumps(doc, indent=2, sort_keys=True, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"vendored {doc['source']['version']} (sha256 {digest[:12]}); now run this script with no arguments")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="exit 1 when the module or the document is stale")
    ap.add_argument("--refresh", action="store_true", help="re-fetch the upstream dataset (needs the network)")
    a = ap.parse_args(argv)
    if a.refresh:
        return refresh()
    doc = _vendored()
    if hashlib.sha256(_extract_text(doc["KSI"]).encode()).hexdigest() != doc["source"]["extract_sha256"]:
        print(f"{VENDOR} does not hash to the extract_sha256 it records", file=sys.stderr)
        return 1
    # The module has to be on disk before the document can be rendered: the document is rendered FROM the module,
    # so that the curated prose and the generated tables cannot disagree.
    mod = module_text(doc)
    stale = [MODULE.name] if MODULE.read_text(encoding="utf-8") != mod else []
    if not a.check:
        MODULE.write_text(mod, encoding="utf-8")
    md = doc_text(doc)
    if a.check:
        if DOC.read_text(encoding="utf-8") != md:
            stale.append(DOC.name)
        if stale:
            print(f"stale, run python scripts/fedramp_ksi.py: {', '.join(stale)}", file=sys.stderr)
            return 1
        from kube_noob.audit import fedramp

        print(
            f"FedRAMP KSI crosswalk is current ({len(fedramp.INDICATORS)} indicators, "
            f"{len(fedramp.FAMILIES)} families, dataset {fedramp.DATASET_VERSION})"
        )
        return 0
    DOC.write_text(md, encoding="utf-8")
    print(f"wrote {MODULE.name} and {DOC.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
